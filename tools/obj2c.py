#!/usr/bin/env python3
"""Convert downloaded CC0 Wavefront OBJ meshes into compact PSP GU vertex arrays."""
from pathlib import Path
import math
import sys

ROOT = Path(__file__).resolve().parents[1]
ASSET_DIR = ROOT / "assets" / "models"
OUT = ROOT / "src" / "models_generated.h"

MODELS = [
    ("pistol", "pistol.obj", (92, 103, 117)),
    ("barrel", "barrel.obj", (157, 78, 39)),
    ("crate", "crate.obj", (164, 113, 59)),
    ("soda_can", "soda_can.obj", (52, 135, 213)),
    ("soda_bottle", "soda_bottle.obj", (63, 171, 124)),
    ("tree", "tree.obj", (55, 133, 61)),
    ("rock", "rock.obj", (119, 126, 132)),
]
LIGHT = (0.35, 0.82, -0.45)
LL = math.sqrt(sum(x*x for x in LIGHT))
LIGHT = tuple(x/LL for x in LIGHT)

def parse_obj(path):
    vertices, faces = [], []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        if fields[0] == "v" and len(fields) >= 4:
            xyz = tuple(float(x) for x in fields[1:4])
            rgb = None
            if len(fields) >= 7:
                try:
                    rgb = tuple(max(0.0, min(1.0, float(x))) for x in fields[4:7])
                except ValueError:
                    rgb = None
            vertices.append((xyz, rgb))
        elif fields[0] == "f" and len(fields) >= 4:
            idxs = []
            for token in fields[1:]:
                raw_idx = int(token.split("/")[0])
                idxs.append(raw_idx - 1 if raw_idx > 0 else len(vertices) + raw_idx)
            for j in range(1, len(idxs)-1):
                tri = (idxs[0], idxs[j], idxs[j+1])
                if min(tri) < 0 or max(tri) >= len(vertices):
                    raise ValueError(f"{path}: face index out of range: {tri}")
                faces.append(tri)
    if not vertices or not faces:
        raise ValueError(f"{path}: OBJ has no renderable geometry")
    return vertices, faces

def pack_color(r, g, b):
    return (255 << 24) | (b << 16) | (g << 8) | r

def fmt(v):
    if abs(v) < 0.0000005:
        v = 0.0
    return f"{v:.6f}f"

def emit():
    lines = [
        "/* Generated by tools/obj2c.py from CC0 OBJ assets. Do not edit. */",
        "#ifndef PSP3D_MODELS_GENERATED_H",
        "#define PSP3D_MODELS_GENERATED_H",
        ""
    ]
    total_triangles = 0
    for name, filename, base in MODELS:
        path = ASSET_DIR / filename
        vertices, faces = parse_obj(path)
        positions = [v[0] for v in vertices]
        mins = [min(v[k] for v in positions) for k in range(3)]
        maxs = [max(v[k] for v in positions) for k in range(3)]
        center = [(mins[k] + maxs[k]) * 0.5 for k in range(3)]
        radius = max(math.sqrt(sum((p[k]-center[k])**2 for k in range(3))) for p in positions)
        rows = []
        for tri in faces:
            p0, p1, p2 = [vertices[i][0] for i in tri]
            a = tuple(p1[k]-p0[k] for k in range(3))
            b = tuple(p2[k]-p0[k] for k in range(3))
            n = (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
            nl = math.sqrt(sum(x*x for x in n)) or 1.0
            n = tuple(x/nl for x in n)
            shade = 0.54 + 0.46 * abs(sum(n[k]*LIGHT[k] for k in range(3)))
            for vi in tri:
                p, vertex_rgb = vertices[vi]
                rgb = base
                if vertex_rgb is not None and min(vertex_rgb) < 0.995:
                    rgb = tuple(int(base[k] * vertex_rgb[k]) for k in range(3))
                r, g, bl = [max(0, min(255, int(c*shade))) for c in rgb]
                rows.append(f"    {{ 0x{pack_color(r, g, bl):08x}u, {fmt(p[0])}, {fmt(p[1])}, {fmt(p[2])} }},")
        lines.append(f"static const Vertex mesh_{name}_vertices[] __attribute__((aligned(16))) = {{")
        lines.extend(rows)
        lines.append("};")
        lines.append(
            f"static const MeshDef MESH_{name.upper()} = {{ mesh_{name}_vertices, "
            f"{len(rows)}, {fmt(center[0])}, {fmt(center[1])}, {fmt(center[2])}, "
            f"{fmt(radius)}, {fmt(maxs[1]-mins[1])} }};"
        )
        lines.append("")
        total_triangles += len(faces)
        print(f"{filename}: {len(faces)} triangles / {len(rows)} GU vertices")
    lines.extend(["#endif", ""])
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT} ({total_triangles} triangles total)")

if __name__ == "__main__":
    try:
        emit()
    except Exception as exc:
        print(f"OBJ conversion failed: {exc}", file=sys.stderr)
        raise
